/// The same cards as [cardCatalog], looked up by id. Anything that
/// stores just a card id (like a [Deck]) uses this to resolve the
/// full card details.
final Map<String, GameCard> cardCatalogById = {
  for (final card in cardCatalog) card.id: card,
};

// ---------------------------------------------------------------------------
// How to add a new card
// ---------------------------------------------------------------------------
// 1. Add a new `GameCard(...)` entry to the `cardCatalog` list above with a
//    unique `id`.
// 2. Pick an `attackCost` from 1 (weak) to 6 (strongest) and give it HP
//    and attack that roughly match the other cards at that cost, so the
//    game stays balanced.
// 3. Set `artwork` to 'assets/cards/animals/<id>.png' and drop a PNG at
//    that path (see assets/cards/README.md for the image spec).
//    If you don't have art yet, leave `artwork` as '' — every screen
//    that displays cards already falls back to a placeholder icon.
// That's it: the collection, deck builder, and game board screens all
// read from `cardCatalog`, so a new entry shows up everywhere
// automatically with no other code changes.
